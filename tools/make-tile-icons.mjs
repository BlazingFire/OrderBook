// Turns the Basic Home tile artwork (docs/design/home-tiles/*.svg) into the
// inline React components of ui/src/tileIcons.tsx. Run after changing a tile:
//   node tools/make-tile-icons.mjs && npx prettier --write ui/src/tileIcons.tsx
// The shapes, colours and gradients are copied as drawn; only the JSX attribute
// names change, the ids become per-instance (useId), and the metadata is dropped.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const source = join(root, 'docs', 'design', 'home-tiles');

/** Tile file -> module id (the NAV_ICONS key, or the New Order tile's `newLead`). */
const TILES = {
  'new-order': 'newLead',
  dashboard: 'dashboard',
  'pending-orders': 'leads',
  'final-orders': 'orders',
  conflicts: 'conflicts',
  chatroom: 'chatroom',
  printroom: 'printroom',
  reports: 'reports',
  products: 'products',
  parties: 'parties',
  'party-access': 'partyAccess',
  lists: 'lists',
  settings: 'settings',
  'app-update': 'updates',
  'notice-board': 'notices',
  'office-panels': 'panels',
  'roles-users': 'access',
  fields: 'fields',
  'activity-log': 'logs',
  'recycle-bin': 'recycleBin',
  integrations: 'integrations',
};

const pascal = (name) => name.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());

function toJsx(file, name) {
  const svg = readFileSync(join(source, `${file}.svg`), 'utf8');
  const body = svg
    .replace(/^[\s\S]*?<\/metadata>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/ ([a-z]+)-([a-z]+)=/g, (_, a, b) => ` ${a}${b[0].toUpperCase()}${b.slice(1)}=`)
    .replace(new RegExp(`id="ob-${file}-(\\w+)"`, 'g'), 'id={`${u}-$1`}')
    .replace(new RegExp(`="url\\(#ob-${file}-(\\w+)\\)"`, 'g'), '={`url(#${u}-$1)`}');
  if (body.includes(`ob-${file}-`)) throw new Error(`${file}: an id was left unconverted`);
  return `function ${name}({ size = 80 }: TileProps) {
  const u = useTileId();
  return (
    <svg viewBox="0 0 96 96" width={size} height={size} aria-hidden="true" focusable="false">
      ${body}
    </svg>
  );
}`;
}

const components = Object.entries(TILES).map(([file, id]) => ({ id, name: `${pascal(file)}Tile`, file }));

const out = `/**
 * The colourful Basic Home tiles, one per module (the one place the chrome
 * carries colour; docs/DESIGN_SYSTEM.md, "Basic Home tiles").
 *
 * GENERATED by tools/make-tile-icons.mjs from docs/design/home-tiles/*.svg;
 * change the artwork there and run the script again rather than editing here.
 */

import { useId, type ComponentType } from 'react';

import type { NavIconId } from './navIcons';

type TileProps = { size?: number };

/** A per-instance id prefix, so two copies of a tile on one page do not share gradients. */
function useTileId(): string {
  return \`ob-tile\${useId().replace(/[^a-zA-Z0-9_-]/g, '')}\`;
}

${components.map((c) => toJsx(c.file, c.name)).join('\n\n')}

/** Module id -> tile. A module with no entry keeps its line icon on a plain face. */
export const TILE_ICONS: Partial<Record<NavIconId | 'newLead', ComponentType<TileProps>>> = {
${components.map((c) => `  ${c.id}: ${c.name},`).join('\n')}
};
`;

writeFileSync(join(root, 'ui', 'src', 'tileIcons.tsx'), out);
